import type { Finding } from "../types";

interface FindingDetailProps {
  finding: Finding | null;
}

function pretty(value: unknown): string {
  try {
    return JSON.stringify(value, null, 2);
  } catch {
    return String(value);
  }
}

export default function FindingDetail({ finding }: FindingDetailProps) {
  if (!finding) {
    return (
      <section className="panel detail-panel">
        <header className="panel-head">
          <h2>Finding detail</h2>
          <span className="muted">none selected</span>
        </header>
        <p className="muted">Select a finding to inspect evidence, PoC and enrichment.</p>
      </section>
    );
  }

  const poc = finding.poc;

  return (
    <section className="panel detail-panel">
      <header className="panel-head">
        <h2>Finding detail</h2>
        <span className="muted">{finding.source}</span>
      </header>

      <h3 className="detail-title">{finding.title}</h3>
      <p className="muted">{finding.description}</p>

      <dl className="kv">
        <div>
          <dt>Severity</dt>
          <dd>{finding.severity}</dd>
        </div>
        <div>
          <dt>Confidence</dt>
          <dd>{Math.round(finding.confidence)}</dd>
        </div>
        <div>
          <dt>Baseline confidence</dt>
          <dd>{Math.round(finding.baseline_confidence)}</dd>
        </div>
        <div>
          <dt>AI adjusted</dt>
          <dd>{finding.ai_adjusted ? "yes" : "no"}</dd>
        </div>
        <div>
          <dt>Verified</dt>
          <dd>{finding.verified ? "yes" : "no"}</dd>
        </div>
        <div>
          <dt>Category</dt>
          <dd>{finding.category || "—"}</dd>
        </div>
        <div>
          <dt>Asset</dt>
          <dd className="mono">{finding.asset || "—"}</dd>
        </div>
        <div>
          <dt>Attack surface</dt>
          <dd>{finding.attack_surface || "—"}</dd>
        </div>
      </dl>

      {finding.ai_analysis ? (
        <section className="subsection">
          <h4>AI analysis</h4>
          <p className="ai-analysis">{finding.ai_analysis}</p>
        </section>
      ) : null}

      <section className="subsection">
        <h4>Evidence</h4>
        {finding.evidence.length === 0 ? (
          <p className="muted">No evidence collected.</p>
        ) : (
          <ul className="evidence-list">
            {finding.evidence.map((item, index) => (
              <li key={`${item.source}-${index}`}>
                <div className="evidence-head">
                  <span className="badge badge-quiet">{item.source}</span>
                  <span>{item.summary}</span>
                </div>
                <pre className="code-block">{pretty(item.raw)}</pre>
              </li>
            ))}
          </ul>
        )}
      </section>

      <section className="subsection">
        <h4>Proof of concept</h4>
        {!poc ? (
          <p className="muted">No PoC bundle for this finding.</p>
        ) : (
          <>
            <p className="muted small">Generated by {poc.generated_by}.</p>

            {poc.steps_to_reproduce.length > 0 ? (
              <>
                <h5>Steps to reproduce</h5>
                <ol className="steps">
                  {poc.steps_to_reproduce.map((step, index) => (
                    <li key={index}>{step}</li>
                  ))}
                </ol>
              </>
            ) : null}

            {poc.request_example ? (
              <>
                <h5>Request</h5>
                <pre className="code-block">{poc.request_example}</pre>
              </>
            ) : null}

            {poc.response_example ? (
              <>
                <h5>Response</h5>
                <pre className="code-block">{poc.response_example}</pre>
              </>
            ) : null}

            {poc.impact ? (
              <>
                <h5>Impact</h5>
                <p>{poc.impact}</p>
              </>
            ) : null}

            {poc.remediation ? (
              <>
                <h5>Remediation</h5>
                <p>{poc.remediation}</p>
              </>
            ) : null}

            {poc.screenshot_guide.length > 0 ? (
              <>
                <h5>Screenshot guide</h5>
                <ol className="steps">
                  {poc.screenshot_guide.map((step, index) => (
                    <li key={index}>{step}</li>
                  ))}
                </ol>
              </>
            ) : null}

            {poc.video_script.length > 0 ? (
              <>
                <h5>Video script</h5>
                <ol className="steps">
                  {poc.video_script.map((step, index) => (
                    <li key={index}>{step}</li>
                  ))}
                </ol>
              </>
            ) : null}

            {poc.bounty_report ? (
              <>
                <h5>Bounty report</h5>
                <pre className="code-block">{poc.bounty_report}</pre>
              </>
            ) : null}
          </>
        )}
      </section>

      <section className="subsection">
        <h4>Enrichment</h4>
        {finding.enrichment.length === 0 ? (
          <p className="muted">No enrichment data.</p>
        ) : (
          <pre className="code-block">{pretty(finding.enrichment)}</pre>
        )}
      </section>

      {finding.references.length > 0 ? (
        <section className="subsection">
          <h4>References</h4>
          <ul className="reference-list">
            {finding.references.map((reference, index) => (
              <li key={index}>
                <a href={reference} target="_blank" rel="noreferrer noopener">
                  {reference}
                </a>
              </li>
            ))}
          </ul>
        </section>
      ) : null}

      <section className="subsection">
        <h4>Raw payload</h4>
        <pre className="code-block">{pretty(finding.raw)}</pre>
      </section>
    </section>
  );
}
